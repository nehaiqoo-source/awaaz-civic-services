// Builds (1) the bookmarklet/web overlay served from /public and (2) the Chrome and Firefox extensions.
import { build } from 'esbuild'
import { copyFile, cp, mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const apiBase = process.env.AWAAZ_API_BASE || 'https://awaaz-civic.vercel.app'
const common = {
  bundle: true,
  format: 'iife',
  target: ['chrome110', 'firefox128', 'safari16'],
  minify: true,
  legalComments: 'none',
  define: { __API_BASE__: JSON.stringify(apiBase) },
  tsconfig: path.join(root, 'tsconfig.json'),
  logLevel: 'info',
}

// 1. Web overlay (bookmarklet / mobile browsers). Reads its API base from window.__AWAAZ__.
await build({ ...common, entryPoints: [path.join(root, 'overlay/main.ts')], outfile: path.join(root, 'public/awaaz-overlay.js') })

// 1b. Mobile app: the same overlay as a string to inject into the built-in browser, plus the shared bridge protocol.
const generated = path.join(root, 'mobile/src/generated')
await mkdir(generated, { recursive: true })
const overlaySource = await readFile(path.join(root, 'public/awaaz-overlay.js'), 'utf8')
await writeFile(
  path.join(generated, 'overlay-bundle.ts'),
  `// GENERATED by scripts/build-ext.mjs from overlay/. Do not edit.\nexport const OVERLAY_SOURCE: string = ${JSON.stringify(overlaySource)}\n`,
)
const protocolSource = await readFile(path.join(root, 'overlay/bridge-protocol.ts'), 'utf8')
await writeFile(path.join(generated, 'bridge-protocol.ts'), `// GENERATED copy of overlay/bridge-protocol.ts by scripts/build-ext.mjs. Do not edit.\n${protocolSource}`)

// 2. Extensions.
for (const target of ['chrome', 'firefox']) {
  const out = path.join(root, 'extension/dist', target)
  await mkdir(out, { recursive: true })
  for (const name of ['content', 'background', 'options']) {
    await build({ ...common, entryPoints: [path.join(root, `extension/src/${name}.ts`)], outfile: path.join(out, `${name}.js`) })
  }
  await copyFile(path.join(root, `extension/manifest.${target}.json`), path.join(out, 'manifest.json'))
  await copyFile(path.join(root, 'extension/options.html'), path.join(out, 'options.html'))
  await cp(path.join(root, 'extension/icons'), path.join(out, 'icons'), { recursive: true })
}
console.log(`Built with API base ${apiBase}`)
